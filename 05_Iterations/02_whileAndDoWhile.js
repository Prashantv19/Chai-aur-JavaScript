//While Loop
let index = 0
while (index <= 10) {
    // console.log(`value of index is ${index}`);
    index= index+2    
}
//------------------------------
let myArray = ["Ironman", "Thor", "Spiderman","Capton"]

let arr = 0
while(arr < myArray.length){
    // console.log(`value of index is ${myArray[arr]}`);
    arr = arr+1
}
